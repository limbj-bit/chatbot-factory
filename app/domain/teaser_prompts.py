def get_teaser_prompts(industry: str, bot_name: str) -> List[str]:
    """Return teaser lines for an industry, with bot name filled in."""
    key = (industry or "general").strip().lower()
    templates = _INDUSTRY_TEASERS.get(key) or _INDUSTRY_TEASERS["general"]
    bot = (bot_name or "상담봇").strip() or "상담봇"
    return [t.replace("{bot}", bot) for t in templates]
